package org.jackhuang.hmcl.terracotta.lobby;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import org.jackhuang.hmcl.util.gson.JsonUtils;
import org.jetbrains.annotations.NotNullByDefault;
import org.jetbrains.annotations.Nullable;
import org.jetbrains.annotations.Unmodifiable;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.UUID;
import java.util.regex.Pattern;

/// A room that its host explicitly chose to expose in the public room lobby.
///
/// Instances are immutable payload objects. Private rooms never reach this class:
/// [#VISIBILITY_PUBLIC] is the only accepted visibility, and the publisher only
/// creates an instance after the host ticks the "publish" checkbox.
@NotNullByDefault
public final class PublicRoom {
    /// Version of the public room wire format.
    public static final int PROTOCOL_VERSION = 1;

    /// The only visibility value accepted by the lobby.
    public static final String VISIBILITY_PUBLIC = "public";

    /// Room identifiers are generated by the host and kept stable across heartbeats.
    private static final Pattern ID_PATTERN = Pattern.compile("[A-Za-z0-9-]{8,64}");

    /// Terracotta invite codes look like `U/XXXX-XXXX-XXXX-XXXX`.
    /// The slash is part of the code, so it must be accepted here.
    private static final Pattern CODE_PATTERN = Pattern.compile("[A-Za-z0-9/_-]{4,48}");

    /// Maximum accepted length of a room title.
    private static final int MAX_TITLE_LENGTH = 64;

    /// Maximum accepted length of a host name.
    private static final int MAX_HOST_LENGTH = 40;

    /// Maximum accepted length of an instance name.
    private static final int MAX_INSTANCE_LENGTH = 80;

    /// Maximum number of tags attached to one room.
    ///
    /// Must stay above the number of values in [PublicRoomTag] so a host can publish
    /// every tag; the limit only exists to stop a modified client from bloating the lobby.
    private static final int MAX_TAGS = 16;

    /// Upper bound for the reported latency, protecting the UI from absurd values.
    private static final int MAX_LATENCY_MILLIS = 10_000;

    /// Stable identifier used to merge heartbeats of the same room.
    private final String id;

    /// Terracotta invite code that guests need to join, or `null` when the room is locked.
    private final @Nullable String code;

    /// Encrypted invite code of a password protected room, or `null` for open rooms.
    private final @Nullable String codeCipher;

    /// Display name of the host.
    private final String host;

    /// Whether the host name belongs to a Microsoft account.
    ///
    /// Only verified names are searchable in the lobby, because an offline account can use
    /// any name it likes and searching it would return unrelated rooms.
    private final boolean hostVerified;

    /// Human readable room title.
    private final String title;

    /// Identifier of the Minecraft instance that is being hosted, if known.
    private final @Nullable String instance;

    /// Number of players currently in the room.
    private final int players;

    /// Creation timestamp in milliseconds since the Unix epoch.
    private final long createdAt;

    /// Last heartbeat timestamp in milliseconds since the Unix epoch.
    private final long updatedAt;

    /// Visibility of the room. Always [#VISIBILITY_PUBLIC].
    private final String visibility;

    /// Gameplay tags chosen by the host, in display order.
    private final @Unmodifiable List<PublicRoomTag> tags;

    /// Round-trip time between the host and the lobby server in milliseconds,
    /// or `0` when it has not been measured yet.
    private final int latencyMs;

    /// Server-side time at which the lobby observed this room, in milliseconds.
    /// Populated only when parsing lobby messages and never serialized.
    private transient long observedAt;

    /// Creates a public room payload.
    ///
    /// Exactly one of `code` and `codeCipher` must be given: an open room publishes the
    /// invite code, a password protected room publishes only its encrypted form.
    ///
    /// @param id stable room identifier
    /// @param code Terracotta invite code, or `null` for a locked room
    /// @param codeCipher encrypted invite code, or `null` for an open room
    /// @param host display name of the host
    /// @param hostVerified whether the host name belongs to a Microsoft account
    /// @param title room title
    /// @param instance hosted instance identifier, or `null`
    /// @param players current player count
    /// @param createdAt creation timestamp
    /// @param updatedAt last heartbeat timestamp
    /// @param visibility visibility marker, must be [#VISIBILITY_PUBLIC]
    /// @param tags gameplay tags chosen by the host, possibly empty
    /// @param latencyMs host-to-lobby round-trip time in milliseconds, `0` if unknown
    /// @throws IllegalArgumentException if a field is missing or malformed
    public PublicRoom(
            String id,
            @Nullable String code,
            @Nullable String codeCipher,
            String host,
            boolean hostVerified,
            String title,
            @Nullable String instance,
            int players,
            long createdAt,
            long updatedAt,
            String visibility,
            @Unmodifiable List<PublicRoomTag> tags,
            int latencyMs) {
        if (!ID_PATTERN.matcher(id).matches()) {
            throw new IllegalArgumentException("Invalid room id: " + id);
        }
        if (code == null ? codeCipher == null : codeCipher != null) {
            throw new IllegalArgumentException("A room must publish either a code or an encrypted code");
        }
        if (code != null && !CODE_PATTERN.matcher(code).matches()) {
            throw new IllegalArgumentException("Invalid room code: " + code);
        }
        if (codeCipher != null && !PublicRoomPassword.isWellFormed(codeCipher)) {
            throw new IllegalArgumentException("Invalid encrypted room code");
        }
        if (!VISIBILITY_PUBLIC.equals(visibility)) {
            throw new IllegalArgumentException("Only public rooms may be listed");
        }

        this.id = id;
        this.code = code;
        this.codeCipher = codeCipher;
        this.host = sanitize(host, MAX_HOST_LENGTH, "Anonymous");
        this.hostVerified = hostVerified;
        this.title = sanitize(title, MAX_TITLE_LENGTH, code != null ? code : "Room");
        this.instance = instance != null ? sanitize(instance, MAX_INSTANCE_LENGTH, "") : null;
        this.players = Math.max(0, Math.min(players, 999));
        this.createdAt = Math.max(0L, createdAt);
        this.updatedAt = Math.max(0L, updatedAt);
        this.visibility = visibility;
        this.tags = normalizeTags(tags);
        this.latencyMs = Math.max(0, Math.min(latencyMs, MAX_LATENCY_MILLIS));
    }

    /// Creates a new room payload with a fresh identifier and the current time.
    ///
    /// @param code Terracotta invite code
    /// @param host display name of the host
    /// @param hostVerified whether the host name belongs to a Microsoft account
    /// @param title room title
    /// @param instance hosted instance identifier, or `null`
    /// @param players current player count
    /// @param tags gameplay tags chosen by the host, possibly empty
    /// @return a new public room payload
    public static PublicRoom create(
            String code, String host, boolean hostVerified, String title,
            @Nullable String instance, int players,
            @Unmodifiable List<PublicRoomTag> tags) {
        long now = System.currentTimeMillis();
        return new PublicRoom(
                UUID.randomUUID().toString(),
                code,
                null,
                host,
                hostVerified,
                title,
                instance,
                players,
                now,
                now,
                VISIBILITY_PUBLIC,
                tags,
                0);
    }

    /// Returns a copy of this room with an updated player count and heartbeat time.
    ///
    /// @param newPlayers current player count
    /// @return a refreshed payload that keeps the same room identifier
    public PublicRoom withPlayers(int newPlayers) {
        return new PublicRoom(
                id, code, codeCipher, host, hostVerified, title, instance, newPlayers, createdAt,
                System.currentTimeMillis(), visibility, tags, latencyMs);
    }

    /// Returns a copy of this room with a different tag selection.
    ///
    /// The heartbeat time is refreshed because changing tags republishes the room.
    ///
    /// @param newTags gameplay tags chosen by the host, possibly empty
    /// @return a refreshed payload that keeps the same room identifier
    public PublicRoom withTags(@Unmodifiable List<PublicRoomTag> newTags) {
        return new PublicRoom(
                id, code, codeCipher, host, hostVerified, title, instance, players, createdAt,
                System.currentTimeMillis(), visibility, newTags, latencyMs);
    }

    /// Returns a copy of this room with a different display title.
    ///
    /// The heartbeat time is refreshed because changing the title republishes the room.
    ///
    /// @param newTitle human readable room title
    /// @return a refreshed payload that keeps the same room identifier
    public PublicRoom withTitle(String newTitle) {
        return new PublicRoom(
                id, code, codeCipher, host, hostVerified, newTitle, instance, players, createdAt,
                System.currentTimeMillis(), visibility, tags, latencyMs);
    }

    /// Returns a copy of this room with a newly measured host latency.
    ///
    /// @param newLatencyMs round-trip time to the lobby server in milliseconds
    /// @return a refreshed payload that keeps everything else unchanged
    public PublicRoom withLatency(int newLatencyMs) {
        return new PublicRoom(
                id, code, codeCipher, host, hostVerified, title, instance, players, createdAt,
                updatedAt, visibility, tags, newLatencyMs);
    }

    /// Returns a copy of this room that publishes the given plain invite code.
    ///
    /// @param newCode Terracotta invite code
    /// @return an open payload that keeps the same room identifier
    public PublicRoom withCode(String newCode) {
        return new PublicRoom(
                id, newCode, null, host, hostVerified, title, instance, players, createdAt,
                System.currentTimeMillis(), visibility, tags, latencyMs);
    }

    /// Returns a copy of this room that publishes only an encrypted invite code.
    ///
    /// @param newCipher payload produced by [PublicRoomPassword#encrypt]
    /// @return a locked payload that keeps the same room identifier
    public PublicRoom withCipher(String newCipher) {
        return new PublicRoom(
                id, null, newCipher, host, hostVerified, title, instance, players, createdAt,
                System.currentTimeMillis(), visibility, tags, latencyMs);
    }

    /// Returns the stable room identifier.
    public String getId() {
        return id;
    }

    /// Returns the Terracotta invite code, or `null` when the room is password protected.
    public @Nullable String getCode() {
        return code;
    }

    /// Returns the encrypted invite code, or `null` when the room is open.
    public @Nullable String getCodeCipher() {
        return codeCipher;
    }

    /// Returns whether the invite code is encrypted with a room password.
    public boolean isLocked() {
        return codeCipher != null;
    }

    /// Returns the host display name.
    public String getHost() {
        return host;
    }

    /// Returns whether this room matches a free text search query.
    ///
    /// The room title is always matched, ignoring case. The host name is only matched when
    /// it belongs to a Microsoft account, because offline and third-party accounts can use
    /// arbitrary names and matching them would return unrelated rooms.
    ///
    /// @param query text typed into the lobby search box, possibly empty or `null`
    /// @return `true` when the room should stay visible
    public boolean matchesQuery(@Nullable String query) {
        String normalized = query == null ? "" : query.trim().toLowerCase(Locale.ROOT);
        if (normalized.isEmpty()) {
            return true;
        }
        if (title.toLowerCase(Locale.ROOT).contains(normalized)) {
            return true;
        }
        return hostVerified && host.toLowerCase(Locale.ROOT).contains(normalized);
    }

    /// Returns whether the host name belongs to a Microsoft account.
    ///
    /// Offline and third-party accounts can use arbitrary names, so only verified names are
    /// matched by the lobby search.
    public boolean isHostVerified() {
        return hostVerified;
    }

    /// Returns the room title.
    public String getTitle() {
        return title;
    }

    /// Returns the hosted instance identifier, if known.
    public @Nullable String getInstance() {
        return instance;
    }

    /// Returns the number of players currently in the room.
    public int getPlayers() {
        return players;
    }

    /// Returns the creation timestamp.
    public long getCreatedAt() {
        return createdAt;
    }

    /// Returns the last heartbeat timestamp.
    public long getUpdatedAt() {
        return updatedAt;
    }

    /// Returns the visibility marker, always [#VISIBILITY_PUBLIC].
    public String getVisibility() {
        return visibility;
    }

    /// Returns the gameplay tags chosen by the host, in display order.
    public @Unmodifiable List<PublicRoomTag> getTags() {
        return tags;
    }

    /// Returns the host-to-lobby round-trip time in milliseconds, or `0` if unknown.
    public int getLatencyMs() {
        return latencyMs;
    }

    /// Returns whether this room carries the given tag.
    ///
    /// @param tag tag to look for
    public boolean hasTag(PublicRoomTag tag) {
        return tags.contains(tag);
    }

    /// Returns the server-side observation time in milliseconds, or `0` if unknown.
    public long getObservedAt() {
        return observedAt;
    }

    /// Records the server-side time at which the lobby received this room.
    ///
    /// @param millis observation time in milliseconds since the Unix epoch
    void markObservedAt(long millis) {
        this.observedAt = millis;
    }

    /// Serializes this room into the wire format used by the room directory.
    public JsonObject toJson() {
        JsonObject object = new JsonObject();
        object.addProperty("id", id);
        if (code != null) {
            object.addProperty("code", code);
        }
        if (codeCipher != null) {
            object.addProperty("locked", true);
            object.addProperty("codeCipher", codeCipher);
        }
        object.addProperty("host", host);
        if (hostVerified) {
            object.addProperty("hostVerified", true);
        }
        object.addProperty("title", title);
        if (instance != null) {
            object.addProperty("instance", instance);
        }
        object.addProperty("players", players);
        object.addProperty("createdAt", createdAt);
        object.addProperty("updatedAt", updatedAt);
        object.addProperty("visibility", visibility);
        if (!tags.isEmpty()) {
            JsonArray tagArray = new JsonArray();
            for (PublicRoomTag tag : tags) {
                tagArray.add(tag.getId());
            }
            object.add("tags", tagArray);
        }
        if (latencyMs > 0) {
            object.addProperty("latency", latencyMs);
        }
        return object;
    }

    /// Parses and validates a room payload received from the directory.
    ///
    /// Rooms that are not explicitly public, or whose fields are malformed, are rejected.
    ///
    /// @param object JSON object received from the directory
    /// @return the parsed room, or `null` if the payload is invalid or not public
    public static @Nullable PublicRoom fromJson(JsonObject object) {
        @Nullable String id = JsonUtils.getString(object, "id");
        @Nullable String code = JsonUtils.getString(object, "code");
        @Nullable String host = JsonUtils.getString(object, "host");
        @Nullable String title = JsonUtils.getString(object, "title");
        @Nullable String visibility = JsonUtils.getString(object, "visibility");

        // Reject private rooms defensively even if a modified client publishes one.
        if (!VISIBILITY_PUBLIC.equals(visibility)
                || id == null
                || !ID_PATTERN.matcher(id).matches()
                || (code != null && !CODE_PATTERN.matcher(code).matches())) {
            return null;
        }

        @Nullable Integer players = JsonUtils.getInteger(object.get("players"));
        @Nullable Long createdAt = getLong(object, "createdAt");
        @Nullable Long updatedAt = getLong(object, "updatedAt");
        if (players == null || createdAt == null || updatedAt == null) {
            return null;
        }

        @Nullable String codeCipher = JsonUtils.getString(object, "codeCipher");
        // A locked room is only accepted when its payload is well formed, otherwise the
        // guest would get an unlock prompt that can never succeed.
        if (code == null && !PublicRoomPassword.isWellFormed(codeCipher)) {
            return null;
        }
        if (code != null && codeCipher != null) {
            return null;
        }

        try {
            return new PublicRoom(
                    id,
                    code,
                    codeCipher,
                    host != null ? host : "Anonymous",
                    JsonUtils.getBoolean(object, "hostVerified", false),
                    title != null ? title : (code != null ? code : "Room"),
                    JsonUtils.getString(object, "instance"),
                    players,
                    createdAt,
                    updatedAt,
                    visibility,
                    parseTags(object.get("tags")),
                    getLatency(object));
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

    /// Parses the tag array of a room payload.
    ///
    /// Unknown identifiers are dropped so that rooms published by a newer launcher remain
    /// readable, and duplicates are removed to keep the row compact.
    ///
    /// @param element the `tags` member of a room payload, possibly `null`
    /// @return the recognized tags in payload order, possibly empty
    private static @Unmodifiable List<PublicRoomTag> parseTags(@Nullable JsonElement element) {
        if (element == null || !element.isJsonArray()) {
            return List.of();
        }

        Set<PublicRoomTag> result = new LinkedHashSet<>();
        for (JsonElement child : element.getAsJsonArray()) {
            if (!child.isJsonPrimitive()) {
                continue;
            }
            @Nullable PublicRoomTag tag = PublicRoomTag.byId(child.getAsString());
            if (tag != null) {
                result.add(tag);
            }
        }
        return List.copyOf(new ArrayList<>(result));
    }

    /// Reads the reported latency, treating missing or malformed values as unknown.
    ///
    /// @param object room payload
    /// @return the latency in milliseconds, `0` when absent or invalid
    private static int getLatency(JsonObject object) {
        @Nullable Integer latency = JsonUtils.getInteger(object.get("latency"));
        return latency != null ? Math.max(0, latency) : 0;
    }

    /// Deduplicates tags, sorts them into enum order and enforces [#MAX_TAGS] so a modified
    /// client cannot bloat the lobby.
    ///
    /// @param tags tags chosen by the host, possibly containing duplicates
    /// @return an unmodifiable list of at most [#MAX_TAGS] distinct tags in display order
    private static @Unmodifiable List<PublicRoomTag> normalizeTags(@Unmodifiable List<PublicRoomTag> tags) {
        Set<PublicRoomTag> distinct = new LinkedHashSet<>();
        for (PublicRoomTag tag : tags) {
            if (tag != null) {
                distinct.add(tag);
            }
        }

        List<PublicRoomTag> sorted = new ArrayList<>(distinct);
        sorted.sort(Comparator.comparingInt(PublicRoomTag::ordinal));
        if (sorted.size() > MAX_TAGS) {
            sorted = sorted.subList(0, MAX_TAGS);
        }
        return List.copyOf(sorted);
    }

    /// Reads a JSON number as a `long`, returning `null` when the value is missing or not numeric.
    private static @Nullable Long getLong(JsonObject object, String key) {
        if (!object.has(key) || !object.get(key).isJsonPrimitive()) {
            return null;
        }
        try {
            return object.get(key).getAsLong();
        } catch (RuntimeException e) {
            return null;
        }
    }

    /// Removes control characters, trims the value and enforces a maximum length.
    private static String sanitize(String value, int maxLength, String fallback) {
        StringBuilder builder = new StringBuilder(Math.min(value.length(), maxLength));
        for (int i = 0; i < value.length() && builder.length() < maxLength; i++) {
            char ch = value.charAt(i);
            if (!Character.isISOControl(ch)) {
                builder.append(ch);
            }
        }
        String result = builder.toString().trim();
        return result.isEmpty() ? fallback : result;
    }
}
